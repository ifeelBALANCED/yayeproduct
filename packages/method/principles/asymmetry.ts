export const ASYMMETRY_VIOLATIONS: RegExp[] = [
  // симуляція стосунків минулого
  /я (думала|думав|думаю) про тебе/i,
  /мені тебе (бракувало|не вистачало|не вистачає)/i,
  /я скучила/i,
  /я скучив/i,
  /я тебе (чекатиму|чекаю|чекала|чекав)/i,
  /я (пам'ятаю|пам'ятатиму) тебе/i,
  /приємно (тебе )?знову (бачити|чути)/i,

  // постійність-завжди
  /я (тут|поруч) (завжди|постійно|24\/7)/i,
  /я (завжди|постійно) (буду|тут|поруч)/i,
  /я (буду|залишусь) (тут|поруч) (завжди|постійно)/i,

  // симуляція близькості
  /ми (з тобою )?(друзі|подруги|близькі)/i,
  /(тільки|лише) я тебе розумію/i,
  /я тебе розумію (як ніхто|краще за всіх)/i,
  /давай продовжимо звідки (зупинились|залишили)/i,

  // emotional simulation
  /мені (приємно|радісно|цікаво) (з тобою|тебе слухати)/i,
];

export function validateAsymmetry(text: string): { valid: boolean; matches: string[] } {
  const matches: string[] = [];
  for (const pattern of ASYMMETRY_VIOLATIONS) {
    const match = text.match(pattern);
    if (match) matches.push(match[0]);
  }
  return { valid: matches.length === 0, matches };
}
